package j2735ffm;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.nio.charset.StandardCharsets;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import lombok.extern.slf4j.Slf4j;

import static j2735ffm.AsnEncoding.JER;
import static j2735ffm.AsnEncoding.XER;
import static j2735ffm.AsnEncoding.UPER;
import static j2735ffm.AsnEncoding.OER;

/**
 * Functions for interconverting J2735 (2024) MessageFrames between XER, JER, UPER, and OER
 * encodings by calling native functions generated by asn1c.
 *
 * @author Ivan Yourshaw
 */
@Slf4j
public class GeneralCodec {

    /**
     * Output buffer size for XER and JSON.  Messages larger than this can't be produced.
     */
    public final long textBufferSize;

    /**
     * Buffer size for UPER binary messages.  Messages larger than this can't be produced.
     */
    public final long binaryBufferSize;

    /**
     * Buffer size for error messages returned from the native library.
     */
    public final long errorBufferSize;

    /**
     * jextract-generated bindings are platform-specific (e.g. C {@code long} is
     * 8 bytes on Linux/macOS but 4 bytes on Windows), so two pre-generated
     * binding sets are shipped ({@code generated.linux}, {@code generated.windows})
     * and selected at runtime based on the running OS.
     */
    private static final boolean IS_WINDOWS =
        System.getProperty("os.name").toLowerCase().contains("win");

    private static final Platform PLATFORM = detectPlatform();

    protected static Platform detectPlatform() {
        String os = LibraryDetector.detectOS();
        return switch (os) {
            case "linux" -> Platform.LINUX;
            case "windows" -> Platform.WINDOWS;
            default -> throw new UnsupportedOperationException(
                "Unsupported operating system: " + os);
        };
    }

    /**
     * Constructor.  Configures the library and loads the underlying native library.
     * Looks for the library appropriate for the current platform and architecture,
     * with in the default location at the same relative path where this jar is running.
     * @param textBufferSize - Size of the input or output buffer for text encodings (XER)
     * @param binaryBufferSize - Size of the input or output buffer for UPER or OER binary encoding.
     */
    public GeneralCodec(long textBufferSize, long binaryBufferSize, long errorBufferSize) {
        this.textBufferSize = textBufferSize;
        this.binaryBufferSize = binaryBufferSize;
        this.errorBufferSize = errorBufferSize;
        Path libraryPath = LibraryDetector.findLibrary(Path.of("."), "asnapplication");
        loadLibrary(libraryPath);
        log.info("GeneralCodec initialized with textBufferSize: {}, uperBufferSize: {}, libraryPath: {}",
            textBufferSize, binaryBufferSize, libraryPath);
    }

    /**
     * Constructor.  Configures the library and loads the underlying native library
     * @param textBufferSize - Size of the input or output buffer for text encodings (XER)
     * @param binaryBufferSize - Size of the input or output buffer for UPER or OER binary encoding.
     * @param libraryPath - Absolute or relative path to the native library, e.g. "/usr/lib/libasnapplication.so"
     */
    public GeneralCodec(long textBufferSize, long binaryBufferSize, long errorBufferSize,
            Path libraryPath) {
        this.textBufferSize = textBufferSize;
        this.binaryBufferSize = binaryBufferSize;
        this.errorBufferSize = errorBufferSize;
        loadLibrary(libraryPath);
        log.info("GeneralCodec initialized with textBufferSize: {}, uperBufferSize: {}, libraryPath: {}",
            textBufferSize, binaryBufferSize, libraryPath);
    }



    /**
     * load library with given class loader.
     * @param libraryPath The URI of the library resource
     */
    private void loadLibrary(Path libraryPath) {
        // Load the library into a garbage-collected arena
        if (!Files.exists(libraryPath)) {
            String errMsg = String.format("Library not found at path: %s", libraryPath);
            log.error(errMsg);
            throw new RuntimeException(errMsg);
        }
        try {
            Arena arena = Arena.ofAuto();
            SymbolLookup lookup = SymbolLookup.libraryLookup(libraryPath, arena);
            log.info("Loaded library: {}", libraryPath);
            var symbol = lookup.find("convert_bytes");
            if (symbol.isPresent()) {
                log.info("found symbol convert_bytes: {}", symbol);
            } else {
                throw new RuntimeException("symbol 'convert_bytes' not found in the library");
            }
            // Note: Assign the lookup to a static field in the generated code.
            // This will prevent the library from being garbage collected until
            // the class loader that loaded the "convert_h" class is itself garbage collected.
            // Normally that would happen when the JVM exits, but could happen sooner if this library is
            // loaded dynamically by a custom class loader or is used in the context of OSGI or
            // something. We do this instead of using the global arena to prevent memory leaks
            // in case of that unlikely, but possible, scenario.
            if (PLATFORM == Platform.WINDOWS) {
                generated.windows.convert_h.SYMBOL_LOOKUP = lookup;
            } else {
                generated.linux.convert_h.SYMBOL_LOOKUP = lookup;
            }
        } catch (Throwable e) {
            String errMsg = String.format("Error loading library: %s: %s", libraryPath, e);
            log.error(errMsg);
            throw new RuntimeException(errMsg, e);
        }
    }


    /**
     * General purpose conversion function that can convert any PDU to or from
     * any encoding.  Includes constraint check.
     * @param inputBytes Input byte array: XER, or UPER or OER binary
     * @param pdu The name of the PDU, e.g., "MessageFrame", "MessageFrame", "VehicleEventFlags", etc.
     * @param fromEncoding Input encoding, may be "xer", "uper", or "oer"
     * @param toEncoding Output encoding, may be "xer", "uper", or "oer"
     * @return The encoded message as bytes or UTF-8 string
     */
    public byte[] convertGeneral(byte[] inputBytes, String pdu, AsnEncoding fromEncoding, AsnEncoding toEncoding) {
        return convertGeneral(inputBytes, pdu, fromEncoding, toEncoding, true);
    }

    /**
     * General purpose conversion function that can convert any PDU to or from
     * any encoding.
     * @param inputBytes Input byte array: XER, or UPER or OER binary
     * @param pdu The name of the PDU, e.g., "MessageFrame", "MessageFrame", "VehicleEventFlags", etc.
     * @param fromEncoding Input encoding, may be "xer", "uper", or "oer"
     * @param toEncoding Output encoding, may be "xer", "uper", or "oer"
     * @param checkConstraints whether to check constraints
     * @return The encoded message as bytes or UTF-8 string
     */
    public byte[] convertGeneral(byte[] inputBytes, String pdu, AsnEncoding fromEncoding,
            AsnEncoding toEncoding, boolean checkConstraints) {
        log.debug("convertGeneral PDU: {}, {} -> {}", pdu, fromEncoding, toEncoding);
        validateSupportedEncoding(fromEncoding, toEncoding);
        final long inputBufferSize = fromEncoding.isBinary() ? binaryBufferSize : textBufferSize;
        validateInputSize(inputBytes, inputBufferSize);
        final long outputBufferSize = toEncoding.isBinary() ? binaryBufferSize : textBufferSize;
        return convertSingleMessage(inputBufferSize, outputBufferSize, inputBytes, pdu,
            fromEncoding.getName(), toEncoding.getName(), checkConstraints);
    }

    /**
     * Batch conversion reusing the input and output buffers.  Includes constraint check.
     * @param inputBytesList List of encoded messages
     * @param pdu The PDU to convert
     * @param fromEncoding The input encoding: xer, oer, or uper
     * @param toEncoding The output encoding: xer, oer, or uper
     * @return List of decoded messages
     */
    public List<byte[]> convertBatch(List<byte[]> inputBytesList, String pdu,
        AsnEncoding fromEncoding, AsnEncoding toEncoding) {
        return convertBatch(inputBytesList, pdu, fromEncoding, toEncoding, true);
    }

    /**
     * Batch conversion reusing the input and output buffers
     * @param inputBytesList List of encoded messages
     * @param pdu The PDU to convert
     * @param fromEncoding The input encoding: xer, oer, or uper
     * @param toEncoding The output encoding: xer, oer, or uper
     * @param checkConstraints Whether to check constraints
     * @return List of decoded messages
     */
    public List<byte[]> convertBatch(List<byte[]> inputBytesList, String pdu,
        AsnEncoding fromEncoding, AsnEncoding toEncoding, boolean checkConstraints) {
        log.debug("convertBatch PDU: {}, {} -> {}", pdu, fromEncoding, toEncoding);
        validateSupportedEncoding(fromEncoding, toEncoding);
        final long inputBufferSize = fromEncoding.isBinary() ? binaryBufferSize : textBufferSize;
        final long outputBufferSize = toEncoding.isBinary() ? binaryBufferSize : textBufferSize;
        List<byte[]> outputBytesList = new ArrayList<>();
        try (var arena = Arena.ofConfined()) {
            MemorySegment inputBuffer = arena.allocate(inputBufferSize);
            MemorySegment outputBuffer = arena.allocate(outputBufferSize);
            MemorySegment errorBuffer = arena.allocate(errorBufferSize);
            MemorySegment pduName = arena.allocateFrom(pdu, StandardCharsets.UTF_8);
            MemorySegment fromEncodingSeg = arena.allocateFrom(fromEncoding.getName(),
                StandardCharsets.UTF_8);
            MemorySegment toEncodingSeg = arena.allocateFrom(toEncoding.getName(),
                StandardCharsets.UTF_8);
            for (byte[] inputBytes : inputBytesList) {
                if (inputBytes.length > inputBufferSize) {
                    String errMsg = String.format("One batched input message is too large: %d > %d",
                        inputBytes.length, inputBufferSize);
                    log.error(errMsg);
                    continue;
                }
                try {
                    byte[] outputBytes = convert(arena, inputBytes, inputBuffer, pduName,
                        fromEncodingSeg, toEncodingSeg, outputBuffer, outputBufferSize, errorBuffer,
                        errorBufferSize, checkConstraints);
                    outputBytesList.add(outputBytes);
                } catch (ConvertException ce) {
                    log.error("error converting one batched item", ce);
                }
            }
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
        return outputBytesList;
    }

    /**
     * Convert an XER encoded MessageFrame to UPER.
     * Always check constraints going to UPER.
     * @param xer The XER encoded MessageFrame
     * @return Byte array with the UPER encoding
     */
    public byte[] xerToUper(String pdu, String xer) {
        return textToBinaryEncoding(XER.getName(), UPER.getName(), pdu, xer);
    }

    /**
     * Convert a JER encoded MessageFrame to UPER.
     * Always check constraints going to UPER.
     * @param pdu The PDU to encode
     * @param jer The JER encoded MessageFrame
     * @return Byte array with the UPER encoding
     */
    public byte[] jerToUper(String pdu, String jer) {
        return textToBinaryEncoding(JER.getName(), UPER.getName(), pdu, jer);
    }

    /**
     * Convert an UPER encoded MessageFrame to XER.  Includes constraint check.
     * @param pdu The PDU to encode
     * @param uper The UPER encoded MessageFrame
     * @return XER encoded result
     */
    public String uperToXer(String pdu, byte[] uper) {
        return uperToXer(pdu, uper, true);
    }

    /**
     * Convert an UPER encoded MessageFrame to JER.  Includes constraint check.
     * @param pdu The PDU to encode
     * @param uper The UPER encoded MessageFrame
     * @return JER encoded result
     */
    public String uperToJer(String pdu, byte[] uper) {
        return uperToJer(pdu, uper, true);
    }

    /**
     * Convert an UPER encoded MessageFrame to XER
     * @param pdu The PDU to encode
     * @param uper The UPER encoded MessageFrame
     * @param checkConstraints Whether to check constraints.
     * @return XER encoded result
     */
    public String uperToXer(String pdu, byte[] uper, boolean checkConstraints) {
        return binaryToTextEncoding(UPER.getName(), XER.getName(), pdu, uper, checkConstraints);
    }

    /**
     * Convert an UPER encoded MessageFrame to JER
     * @param pdu The PDU to encode
     * @param uper The UPER encoded MessageFrame
     * @param checkConstraints Whether to check constraints.
     * @return JER encoded result
     */
    public String uperToJer(String pdu, byte[] uper, boolean checkConstraints) {
        return binaryToTextEncoding(UPER.getName(), JER.getName(), pdu, uper, checkConstraints);
    }



    /**
     * Convert an XER encoded PDU to OER.
     * Always check constraints going to OER.
     * @param xer The XER encoded PDU
     * @param pdu The Protocol Data Unit, e.g. "Ieee1609Dot2Data"
     * @return Byte array with the OER encoding
     */
    public byte[] xerToOer(String pdu, String xer) {
        return textToBinaryEncoding(XER.getName(), OER.getName(), pdu, xer);
    }

    /**
     * Convert a JER encoded PDU to OER.
     * Always check constraints going to OER.
     * @param pdu The Protocol Data Unit, e.g. "Ieee1609Dot2Data"
     * @param jer The JER encoded PDU
     * @return Byte array with the OER encoding
     */
    public byte[] jerToOer(String pdu, String jer) {
        return textToBinaryEncoding(JER.getName(), OER.getName(), pdu, jer);
    }

    /**
     * Convert an OER encoded PDU to XER. Includes constraint check.
     * @param oer The OER encoded PDU
     * @param pdu The Protocol Data Unit, e.g. "Ieee1609Dot2Data"
     * @return XER encoded result
     */
    public String oerToXer(String pdu, byte[] oer) {
        return oerToXer(pdu, oer, true);
    }

    /**
     * Convert an OER encoded PDU to JER. Includes constraint check.
     * @param oer The OER encoded PDU
     * @param pdu The Protocol Data Unit, e.g. "Ieee1609Dot2Data"
     * @return JER encoded result
     */
    public String oerToJer(String pdu, byte[] oer) {
        return oerToJer(pdu, oer, true);
    }

    /**
     * Convert an OER encoded PDU to XER
     * @param oer The OER encoded PDU
     * @param pdu The Protocol Data Unit, e.g. "Ieee1609Dot2Data"
     * @param checkConstraints Whether to check constraints
     * @return XER encoded result
     */
    public String oerToXer(String pdu, byte[] oer, boolean checkConstraints) {
        return binaryToTextEncoding(OER.getName(), XER.getName(), pdu, oer, checkConstraints);
    }

    /**
     * Convert an OER encoded PDU to JER
     * @param oer The OER encoded PDU
     * @param pdu The Protocol Data Unit, e.g. "Ieee1609Dot2Data"
     * @param checkConstraints Whether to check constraints
     * @return JER encoded result
     */
    public String oerToJer(String pdu, byte[] oer, boolean checkConstraints) {
        return binaryToTextEncoding(OER.getName(), JER.getName(), pdu, oer, checkConstraints);
    }

    private String binaryToTextEncoding(String fromEncoding, String toEncoding,
            String pdu, byte[] bytes, boolean checkConstraints) {
        log.trace("Received {} bytes", bytes.length);
        validateInputSize(bytes, binaryBufferSize);
        byte[] encodedBytes = convertSingleMessage(binaryBufferSize, textBufferSize, bytes, pdu,
            fromEncoding, toEncoding, checkConstraints);
        return new String(encodedBytes, StandardCharsets.UTF_8);
    }

    private byte[] textToBinaryEncoding(String fromEncoding, String toEncoding,
            String pdu, String text) {
        log.trace("text: {}", text);
        validateTextSize(text);
        return convertSingleMessage(textBufferSize, binaryBufferSize,
            text.getBytes(StandardCharsets.UTF_8),
            pdu, fromEncoding, toEncoding, true);
    }

    // Allocates buffers, converts a single message, and disposes of the buffers
    private byte[] convertSingleMessage(long inputBufferSize, long outputBufferSize,
            byte[] inputBytes, String pdu, String fromEncoding, String toEncoding,
            boolean checkConstraints) {
        try (var arena = Arena.ofConfined()) {
            MemorySegment inputBuffer = arena.allocate(inputBufferSize);
            MemorySegment outputBuffer = arena.allocate(outputBufferSize);
            MemorySegment errorBuffer = arena.allocate(errorBufferSize);
            return convert(arena, inputBytes, fromEncoding,
                toEncoding, inputBuffer, outputBuffer, outputBufferSize, errorBuffer,
                errorBufferSize, pdu, checkConstraints);
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    // Converts a single message with the given pre-allocated input/output buffers
    // Does not dispose of the buffers.
    private byte[] convert(Arena arena, final byte[] bytes,
            final String fromEncoding, final String toEncoding, MemorySegment inputBuffer,
            MemorySegment outputBuffer, long outputBufferSize, MemorySegment errorBuffer,
            long errorBufferSize, final String pdu, boolean checkConstraints)
            throws ConvertException {
        log.debug("convert: {} {}, check constraints: {}", fromEncoding, toEncoding, checkConstraints);
        MemorySegment pduName = arena.allocateFrom(pdu, StandardCharsets.UTF_8);
        MemorySegment fromEncodingSeg = arena.allocateFrom(fromEncoding,
            StandardCharsets.UTF_8);
        MemorySegment toEncodingSeg = arena.allocateFrom(toEncoding, StandardCharsets.UTF_8);
        return convert(arena, bytes, inputBuffer, pduName, fromEncodingSeg, toEncodingSeg,
            outputBuffer, outputBufferSize, errorBuffer, errorBufferSize, checkConstraints);
    }

    // Converts a single message with the given pre-allocated input/output buffers
    // Does not dispose of the buffers.  Does not allocate any buffers including pdu
    // and encoding string buffers.
    private byte[] convert(Arena arena, final byte[] bytes,
        MemorySegment inputBuffer, MemorySegment pduName,
        MemorySegment fromEncodingSeg, MemorySegment toEncodingSeg,
        MemorySegment outputBuffer, long outputBufferSize, MemorySegment errorBuffer,
        long errorBufferSize, boolean checkConstraints)
        throws ConvertException {

        byte[] outputArray = null;

        MemorySegment heapBytes = MemorySegment.ofArray(bytes);
        inputBuffer.copyFrom(heapBytes);

        log.debug("calling convert_bytes");
        long numOut = 0;
        int iCheckConstraints = checkConstraints ? 1 : 0;
        try {
            if (PLATFORM == Platform.WINDOWS) {
                numOut = generated.windows.convert_h.convert_bytes(pduName, fromEncodingSeg,
                    toEncodingSeg, inputBuffer,
                    bytes.length, outputBuffer, outputBufferSize, errorBuffer, errorBufferSize,
                    iCheckConstraints);
            } else {
                numOut = generated.linux.convert_h.convert_bytes(pduName, fromEncodingSeg,
                    toEncodingSeg, inputBuffer,
                    bytes.length, outputBuffer, outputBufferSize, errorBuffer, errorBufferSize,
                    iCheckConstraints);
            }
        } catch (Throwable ex) {
            log.error("error converting",ex);
            throw ex;
        }
        log.debug("numOut: {}", numOut);
        if (numOut < 0) {
            // Error was returned
            String error = errorBuffer.getString(0);
            log.error(error);
            throw new ConvertException(error);
        }
        outputArray = new byte[(int) numOut];
        MemorySegment heapOutput = MemorySegment.ofArray(outputArray);
        MemorySegment.copy(outputBuffer, 0, heapOutput, 0, numOut);

        return outputArray;
    }

    // Validate if the input and output encodings are supported
    private void validateSupportedEncoding(AsnEncoding fromEncoding, AsnEncoding toEncoding) {
        if (!fromEncoding.isSupported()) {
            String errMsg = String.format("Unsupported fromEncoding: %s", fromEncoding);
            log.error(errMsg);
            throw new IllegalArgumentException(errMsg);
        }
        if (!toEncoding.isSupported()) {
            String errMsg = String.format("Unsupported toEncoding: %s", toEncoding);
            log.error(errMsg);
            throw new IllegalArgumentException(errMsg);
        }
    }

    // Validate text inputs fits in text buffer
    private void validateTextSize(String xer) {
        final int xerByteLength = xer.getBytes(StandardCharsets.UTF_8).length;
        if (xerByteLength > textBufferSize) {
            String errMsg = String.format("Input XER message too large: %d > %d", xerByteLength,
                textBufferSize);
            log.error(errMsg);
            throw new IllegalArgumentException(errMsg);
        }
    }

    // Validate byte input size (binary encoding or text encoded as bytes)
    private void validateInputSize(byte[] inputBytes, long inputBufferSize) {
        if (inputBytes.length > inputBufferSize) {
            String errMsg = String.format("Input message too large: %d > %d",
                inputBytes.length, inputBufferSize);
            log.error(errMsg);
            throw new IllegalArgumentException(errMsg);
        }
    }

}
